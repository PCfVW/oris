//! Reads every `*.jsonl` under `benchmarks/results/<version>/<platform>/` and writes
//! `benchmarks/results/<version>/SUMMARY.md`: per platform, per trace, one row per
//! (harness, allocator) with wall time (median, IQR, range over the timed repetitions),
//! per-operation latency (p99, p99.9, max), and memory (peak resident-set growth and
//! fragmentation). See `benchmarks/methodology.md` for what each number means.
//!
//! ```text
//! cargo run --release [-- <version>]      # default v0.3.0
//! ```
//!
//! If `benchmarks/results/<version>/mimalloc-bench/summary.md` exists, it is appended.

use anyhow::{Context, Result};
use serde_json::Value;
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// Median, exclusive-median quartiles, min and max.
struct Stats {
    median: f64,
    q1: f64,
    q3: f64,
    min: f64,
    max: f64,
}

fn median(sorted: &[f64]) -> f64 {
    let n = sorted.len();
    if n == 0 {
        return f64::NAN;
    }
    if n % 2 == 1 {
        sorted[n / 2]
    } else {
        (sorted[n / 2 - 1] + sorted[n / 2]) / 2.0
    }
}

/// Quartiles by the exclusive-median method: the median of the lower and of the upper
/// half, the overall median excluded when `n` is odd.
fn stats(mut v: Vec<f64>) -> Option<Stats> {
    if v.is_empty() {
        return None;
    }
    v.sort_by(f64::total_cmp);
    let n = v.len();
    let lower = &v[..n / 2];
    let upper = &v[n.div_ceil(2)..];
    Some(Stats {
        median: median(&v),
        q1: if lower.is_empty() {
            v[0]
        } else {
            median(lower)
        },
        q3: if upper.is_empty() {
            v[n - 1]
        } else {
            median(upper)
        },
        min: v[0],
        max: v[n - 1],
    })
}

/// (harness, allocator, trace).
type Key = (String, String, String);

#[derive(Default)]
struct Cell {
    wall_ms: Vec<f64>,
    latency: Option<Value>,
    memory: Option<Value>,
}

fn num(v: &Value, key: &str) -> Option<f64> {
    v.get(key).and_then(Value::as_f64)
}

fn mib(bytes: f64) -> String {
    format!("{:.2}", bytes / (1024.0 * 1024.0))
}

fn main() -> Result<()> {
    let version = std::env::args()
        .nth(1)
        .unwrap_or_else(|| "v0.3.0".to_owned());
    let bench = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
    let results = bench.join("results").join(&version);
    let mut out = String::new();
    let _ = writeln!(out, "# Benchmark results — Oris {version}\n");
    let _ = writeln!(
        out,
        "Generated by `benchmarks/scripts/aggregate` from the raw records next to this file; \
         see [`../../methodology.md`](../../methodology.md) for the protocol and what every \
         column means. Traces: `benchmarks/traces.toml` (bench tier), checksums in \
         `benchmarks/trace-checksums.txt`.\n"
    );
    let _ = writeln!(
        out,
        "**Reading the tables.** *Wall* is the median time to replay the whole trace over 10 \
         timed runs (after 2 warm-up runs), with the interquartile range and the range. \
         *p99 / p99.9 / max* are per-operation latencies from one further run, timer included. \
         *RSS Δ* is how much the resident set grew during one replay in a fresh process; *frag* \
         is RSS Δ divided by the trace's peak live requested bytes (1.0 would be perfect). \
         Allocators other than `orisnik`/`orisnitsa` cannot `resize` in place or `purge`, \
         so those operations are no-ops for them.\n"
    );

    let mut platforms: Vec<PathBuf> = std::fs::read_dir(&results)
        .with_context(|| format!("failed to read {}", results.display()))?
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.is_dir() && p.join("env.json").exists())
        .collect();
    platforms.sort();

    for platform in &platforms {
        let env: Value =
            serde_json::from_str(&std::fs::read_to_string(platform.join("env.json"))?)?;
        let label = env.get("platform").and_then(Value::as_str).unwrap_or("?");
        let _ = writeln!(out, "## {label}\n");
        let field = |k: &str| {
            env.get(k).map_or_else(String::new, |v| {
                v.as_str().map_or_else(|| v.to_string(), str::to_owned)
            })
        };
        let _ = writeln!(
            out,
            "{} — {}, {} logical cores, {} GB RAM ({}); {}; {}; commit `{}`{}, {}.\n",
            field("os"),
            field("cpu"),
            field("logical_cores"),
            field("ram_gb"),
            field("cpu_governor"),
            field("rustc"),
            field("zig"),
            field("commit"),
            if field("dirty") == "true" {
                " (dirty)"
            } else {
                ""
            },
            field("date"),
        );
        let cells = load(platform)?;
        let mut by_trace: BTreeMap<String, Vec<(&Key, &Cell)>> = BTreeMap::new();
        for (key, cell) in &cells {
            by_trace.entry(key.2.clone()).or_default().push((key, cell));
        }
        for (trace, rows) in by_trace {
            let _ = writeln!(out, "### `{trace}`\n");
            let _ = writeln!(
                out,
                "| harness | allocator | wall ms: median (IQR) [range] | p99 ns | p99.9 ns | max µs | RSS Δ MiB | frag |"
            );
            let _ = writeln!(out, "|---|---|---|---:|---:|---:|---:|---:|");
            for ((harness, allocator, _), cell) in rows {
                let wall = stats(cell.wall_ms.clone()).map_or_else(
                    || "—".to_owned(),
                    |s| {
                        format!(
                            "{:.1} ({:.1}–{:.1}) [{:.1}–{:.1}]",
                            s.median, s.q1, s.q3, s.min, s.max
                        )
                    },
                );
                let lat = |k: &str, scale: f64, digits: usize| {
                    cell.latency
                        .as_ref()
                        .and_then(|l| num(l, k))
                        .map_or_else(|| "—".to_owned(), |v| format!("{:.*}", digits, v / scale))
                };
                let mem = cell.memory.as_ref();
                let delta = mem
                    .and_then(|m| num(m, "peak_rss_delta_bytes"))
                    .map_or_else(|| "—".to_owned(), mib);
                let frag = mem
                    .and_then(|m| num(m, "fragmentation"))
                    .map_or_else(|| "—".to_owned(), |f| format!("{f:.2}"));
                let name = if allocator == "orisnik" || allocator == "orisnitsa" {
                    format!("**{allocator}**")
                } else {
                    allocator.clone()
                };
                let _ = writeln!(
                    out,
                    "| {harness} | {name} | {wall} | {} | {} | {} | {delta} | {frag} |",
                    lat("p99_ns", 1.0, 0),
                    lat("p999_ns", 1.0, 0),
                    lat("max_ns", 1000.0, 1),
                );
            }
            let _ = writeln!(out);
        }
    }

    let mb = results.join("mimalloc-bench").join("summary.md");
    if mb.exists() {
        out.push_str(&std::fs::read_to_string(&mb)?);
    }
    let path = results.join("SUMMARY.md");
    std::fs::write(&path, out).with_context(|| format!("failed to write {}", path.display()))?;
    println!("wrote {}", path.display());
    Ok(())
}

/// Every cell of one platform directory, keyed by (harness, allocator, trace).
fn load(dir: &Path) -> Result<BTreeMap<Key, Cell>> {
    let mut cells: BTreeMap<Key, Cell> = BTreeMap::new();
    let mut files: Vec<PathBuf> = std::fs::read_dir(dir)?
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|x| x == "jsonl"))
        .collect();
    files.sort();
    for file in files {
        for line in std::fs::read_to_string(&file)?
            .lines()
            .filter(|l| !l.trim().is_empty())
        {
            let r: Value = serde_json::from_str(line)
                .with_context(|| format!("{}: bad record", file.display()))?;
            let s = |k: &str| r.get(k).and_then(Value::as_str).unwrap_or("?").to_owned();
            let cell = cells
                .entry((s("harness"), s("allocator"), s("trace")))
                .or_default();
            match s("pass").as_str() {
                "wall" => cell.wall_ms.extend(num(&r, "wall_ns").map(|ns| ns / 1e6)),
                "latency" => cell.latency = Some(r),
                "memory" => cell.memory = Some(r),
                _ => {}
            }
        }
    }
    Ok(cells)
}
