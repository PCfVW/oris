"""The purge ablation: every bench trace replayed with and without its `purge` operations.

    python3 purge-ablation.py <bench-rust> <traces-dir> <env.json> <out-dir> [replay]

Runs the three passes of the protocol (methodology.md) plus `breakdown`, each with and without
`--no-purge`, for `orisnik`, the system allocator and mimalloc, and writes every record to
<out-dir>/records.jsonl and the tables to <out-dir>/summary.md. Given the `replay` example
(`cargo build --release --example replay --features trace`), it also counts the OS mappings in
each trace's transition record — those are the same on every platform.
"""
import json
import pathlib
import statistics
import subprocess
import sys

TRACES = ["planner-1m", "parser-1m", "synthetic-small-1m", "synthetic-mixed-1m", "synthetic-large-1m"]
ALLOCATORS = ["orisnik", "system", "mimalloc"]
bench, traces, env_file, out = sys.argv[1], pathlib.Path(sys.argv[2]), sys.argv[3], pathlib.Path(sys.argv[4])
replay = sys.argv[5] if len(sys.argv) > 5 else None
out.mkdir(parents=True, exist_ok=True)
records = open(out / "records.jsonl", "w", newline="\n")


def run(allocator, trace, pass_, purge):
    cmd = [bench, "--allocator", allocator, "--trace", str(traces / f"{trace}.trace"), "--pass", pass_,
           "--env-file", env_file] + ([] if purge else ["--no-purge"])
    lines = [l for l in subprocess.run(cmd, capture_output=True, text=True, check=True).stdout.splitlines() if l.strip()]
    records.writelines(l + "\n" for l in lines)
    return [json.loads(l) for l in lines]


wall, memory, breakdown = {}, {}, {}
for t in TRACES:
    for a in ALLOCATORS:
        for purge in (True, False):
            key = (t, a, purge)
            wall[key] = statistics.median(r["wall_ns"] for r in run(a, t, "wall", purge)) / 1e6
            memory[key] = run(a, t, "memory", purge)[0]
            breakdown[key] = run(a, t, "breakdown", purge)[0]

md = ["# Purge ablation", "", "Generated by `benchmarks/scripts/purge-ablation.py` from `records.jsonl`.", "",
      "## Wall time, ms (median of 10): with purge / without", "",
      "| Trace | " + " | ".join(ALLOCATORS) + " |", "|---" * (len(ALLOCATORS) + 1) + "|"]
for t in TRACES:
    md.append(f"| {t} | " + " | ".join(f"{wall[(t, a, True)]:.1f} / {wall[(t, a, False)]:.1f}" for a in ALLOCATORS) + " |")
md += ["", "## orisnik: peak RSS growth, KiB, and fragmentation: with purge / without", "",
       "| Trace | RSS Δ | fragmentation |", "|---|---|---|"]
for t in TRACES:
    w, n = memory[(t, "orisnik", True)], memory[(t, "orisnik", False)]
    md.append(f"| {t} | {w['peak_rss_delta_bytes'] // 1024} / {n['peak_rss_delta_bytes'] // 1024} "
              f"| {w['fragmentation']:.2f} / {n['fragmentation']:.2f} |")
md += ["", "## orisnik breakdown, heaviest categories: total ms and p99.9 ns, with purge / without", "",
       "| Trace | Category | count | total ms | p99.9 ns |", "|---|---|---|---|---|"]
for t in TRACES:
    w, n = breakdown[(t, "orisnik", True)]["categories"], breakdown[(t, "orisnik", False)]["categories"]
    for c, d in sorted(w.items(), key=lambda kv: -kv[1]["total_ns"])[:4]:
        e = n.get(c)
        after = (f"{e['total_ns'] / 1e6:.1f}", f"{e['p999_ns']}") if e else ("—", "—")
        md.append(f"| {t} | {c} | {d['count']} | {d['total_ns'] / 1e6:.1f} / {after[0]} | {d['p999_ns']} / {after[1]} |")
if replay:
    md += ["", "## OS mappings in the transition record (map b / map t / unmap): with purge / without", "",
           "| Trace | with purge | without |", "|---|---|---|"]
    for t in TRACES:
        cells = []
        for purge in (True, False):
            src = traces / f"{t}.trace"
            path = src if purge else out / f"{t}.nopurge.trace"
            if not purge:
                text = src.read_text()
                path.write_text("\n".join(l for l in text.split("\n") if l.strip() != "purge"), newline="\n")
            rec = subprocess.run([replay, str(path)], capture_output=True, text=True, check=True).stdout
            cells.append(f"{rec.count(chr(10) + '  map b ')} / {rec.count(chr(10) + '  map t ')} / {rec.count(chr(10) + '  unmap ')}")
            if not purge:
                path.unlink()
        md.append(f"| {t} | {cells[0]} | {cells[1]} |")
(out / "summary.md").write_text("\n".join(md) + "\n", newline="\n")
print("\n".join(md))
